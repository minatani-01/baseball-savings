-- ============================================================================
-- Marine Wallet / 0011_profile_avatar
-- ----------------------------------------------------------------------------
-- 自分のプロフィールアイコンをマイページから設定できるようにする。
--
-- 置き場所は 0010 で作った member-avatars バケットを共用する。
-- 同じ「<auth.uid()>/ 配下は本人だけ読み書きできる」ルールで足りるため、
-- バケットを増やしても管理対象が増えるだけで得るものがない。
-- ファイル名の頭で用途を分ける（profile-… / <メンバーID>-…）。
--
-- 共有範囲: 本人だけ。Marine Link の相手からは見えない。
-- 相手に見せるには相手のトークンで読める必要があり、いまの
-- 「自分のフォルダだけ」という単純な規則を崩すことになるため、ここでは広げない。
-- ============================================================================

alter table public.profiles
  add column if not exists avatar_path text;

comment on column public.profiles.avatar_path is
  'member-avatars バケット上のパス。null なら表示名の頭文字を表示する';
