-- Marine Wallet / 0024_members_are_split_members
-- ----------------------------------------------------------------------------
-- 「メンバーに載っている人は、割り勘の人」とする。
--
-- これまでメンバー画面に割り勘の「共有する」チェック（join_split）があり、
-- 外すと割り勘の分担先に出なくなっていた。
-- ただメンバー一覧そのものが割り勘の登場人物なので、
-- 「メンバーだが割り勘には出ない人」という状態を持つ意味が薄い。
-- 割り勘から外したいならメンバーごと消せばよい。
--
-- チェックを UI から外すにあたり、false のまま取り残されると
-- 割り勘に出せなくなって戻す手段が無くなるため、全員 true に揃える。
--
-- 列そのものは残す。0008 で作った split_record_shared_with_me が
-- この列を参照しているため。既定値が true なので、
-- これ以降に作られるメンバーも自動的に割り勘の参加者になる。
--
-- 冪等性: 何度実行しても安全。
-- ============================================================================

update public.split_members
   set join_split = true
 where join_split = false;
